/*
  WHAT: Copies the extension's real quips into site/quips.js for the fridge site.
  WHY: The site has no build step, and the brief says real content only, so the
       notes on the fridge come from the same JSON the extension ships.
  HOW DATA FLOWS: src/data/quips/*.json -> site/quips.js (window.TABBY_QUIPS).
  SEAMS: None. Run with `node scripts/site-quips.cjs` after editing quips.
*/
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const pa = JSON.parse(fs.readFileSync(path.join(root, 'src/data/quips/passive-aggressive.json'), 'utf8'));
const ee = JSON.parse(fs.readFileSync(path.join(root, 'src/data/quips/easter-eggs.json'), 'utf8'));
const byTrigger = {};
for (const q of pa) for (const t of q.triggerTypes) (byTrigger[t] = byTrigger[t] || []).push(q.text);
// Song-lyric eggs stay in the extension but not on the public site.
const LYRICS = /rick-?roll|never gonna/i;
const eggs = ee.filter(e => !LYRICS.test(e.type) && !LYRICS.test(e.quips[0])).map(e => ({ type: e.type, conditions: e.conditions, quip: e.quips[0] }));
const out = '/* Generated by scripts/site-quips.cjs from src/data/quips. Do not edit by hand. */\n' +
  'window.TABBY_QUIPS = ' + JSON.stringify({ all: pa.map(q => q.text), byTrigger, eggs }) + ';\n';
fs.writeFileSync(path.join(root, 'site/quips.js'), out);
console.log('quips:', pa.length, 'eggs:', eggs.length);
